import re
LIST_PATTERNS = {
    # Многоуровневые и обычные цифровые (1., 1.1., 1.2.3, 1))
    "numeric": re.compile(r'^(\d+(?:\.\d+)*)\.?\s*[\)\.]?\s+(.*)'),
    
    # Алфавитные (а), б), а., А.) — с учетом русской и английской раскладки
    "alphabetical": re.compile(r'^([а-яА-Яa-zA-Z])[\)\.]\s+(.*)'),
    
    # Маркированные (-, *, •, –)
    "bullet": re.compile(r'^([-\*•–])\s+(.*)')
}